#!/usr/bin/env node
/**
 * Ports the scene SVGs from design/source/*.dc.html into react-native-svg
 * components under src/themes/scenes/ported/. Run with:
 *
 *   node scripts/port-scenes.js
 *
 * The output is generated: edit the mockup (or this script), not the output.
 * Parts of a scene that react to game state (Tyohar's diyas, Masala Mix's
 * slot reel) are stripped here and drawn by hand-written components instead.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'design/source');
const OUT = path.join(ROOT, 'src/themes/scenes/ported');

const TAGS = {
  g: 'G',
  path: 'Path',
  rect: 'Rect',
  circle: 'Circle',
  ellipse: 'Ellipse',
  polygon: 'Polygon',
  polyline: 'Polyline',
  line: 'Line',
};

// Elements removed before porting because a live component draws them.
const STRIP = {
  // The nine diyas follow the lives count, so DiyaRow draws them.
  Tyohar: [/<g transform="translate\(\d+ \d+\)">[\s\S]*?<\/g>\s*(?=<g transform="translate|$)/g],
  // The slot reel (machine body and window) is animated by SlotReel.
  MasalaMix: [/<rect x="196" y="54"[\s\S]*?(?=<\/g>\s*$)/],
};

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function convert(body, indent) {
  const out = [];
  let depth = 0;
  const re = /<(\/)?([a-z]+)([^>]*?)(\/)?>/g;
  let m;
  while ((m = re.exec(body))) {
    const [, closing, tag, rawAttrs, selfClosing] = m;
    const Comp = TAGS[tag];
    if (!Comp) throw new Error(`Unsupported SVG tag <${tag}>`);
    if (closing) {
      depth -= 1;
      if (tag === 'g') out.push(`${indent}${'  '.repeat(depth)}</G>`);
      continue;
    }
    const attrs = [...rawAttrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)]
      .map(([, k, v]) => `${camel(k)}="${v}"`)
      .join(' ');
    // Look ahead: an element immediately closed becomes self-closing JSX.
    const rest = body.slice(re.lastIndex);
    const immediatelyClosed = new RegExp(`^\\s*</${tag}>`).exec(rest);
    if (selfClosing || (tag !== 'g' && immediatelyClosed)) {
      out.push(`${indent}${'  '.repeat(depth)}<${Comp} ${attrs} />`);
      if (immediatelyClosed) re.lastIndex += immediatelyClosed[0].length;
      continue;
    }
    if (tag === 'g' && immediatelyClosed) {
      re.lastIndex += immediatelyClosed[0].length;
      continue;
    }
    out.push(`${indent}${'  '.repeat(depth)}<${Comp}${attrs ? ' ' + attrs : ''}>`);
    depth += 1;
  }
  return out;
}

const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.dc.html')).sort();
fs.mkdirSync(OUT, { recursive: true });
const index = [];

for (const file of files) {
  const name = file.replace('.dc.html', '');
  const html = fs.readFileSync(path.join(SRC, file), 'utf8');
  const m = html.match(/<svg[^>]*viewBox="0 0 366 (\d+)"[^>]*aria-label="([^"]*)"[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error(`No scene SVG in ${file}`);
  const [, height, label, rawBody] = m;
  let body = rawBody;
  for (const re of STRIP[name] ?? []) body = body.replace(re, '');
  const used = new Set();
  for (const t of body.matchAll(/<([a-z]+)/g)) used.add(TAGS[t[1]]);
  const comp = `${name}Scene`;
  const jsx = convert(body, '      ');
  const src = `// Generated by scripts/port-scenes.js from design/source/${file}. Do not edit.
import { ${[...used].sort().join(', ')} } from 'react-native-svg';

/** ${label}${STRIP[name] ? ' (live parts drawn separately)' : ''} */
export function ${comp}() {
  return (
    <>
${jsx.join('\n')}
    </>
  );
}

export const ${comp}Height = ${height};
export const ${comp}Label = ${JSON.stringify(label)};
`;
  fs.writeFileSync(path.join(OUT, `${name}Scene.tsx`), src);
  index.push(`export * from './${name}Scene';`);
}
fs.writeFileSync(path.join(OUT, 'index.ts'), `// Generated by scripts/port-scenes.js. Do not edit.\n${index.join('\n')}\n`);
console.log(`Ported ${files.length} scenes to ${path.relative(ROOT, OUT)}`);
