/**
 * Builds a condensed brief of a GitHub issue for agent handoffs (#47).
 * Pure functions only: scripts/issue-brief.js fetches the issue and prints the result.
 *
 * Deterministic: it extracts and trims, and never summarises. When a section is
 * missing it says so instead of guessing.
 */

/**
 * @typedef {{ lines: string[], cutLines: number }} BriefSection
 * @typedef {{ number: number, title?: string, type?: 'issue' | 'pr', state?: string }} BriefLink
 * @typedef {{ author: string, role: string | null, title: string | null, kind: 'role' | 'owner',
 *   createdAt: string, url: string, excerpt: string[], cutLines: number }} BriefComment
 * @typedef {{ number: number, title: string, state: string, labels: string[], url: string,
 *   sections: { userStory: BriefSection | null, criteria: BriefSection | null,
 *     priority: BriefSection | null, estimate: BriefSection | null },
 *   links: BriefLink[], files: string[], comments: BriefComment[], cut: string[] }} Brief
 */

const DEFAULT_MAX_LINES = 150;
const EXCERPT_LINES = 6;
const SHORT_EXCERPT_LINES = 3;

/** Sections the issue templates produce, in the order the brief prints them. */
const SECTIONS = [
  { key: 'userStory', label: 'User story', match: /^user story$/i },
  { key: 'criteria', label: 'Acceptance criteria', match: /^acceptance criteria$/i },
  { key: 'priority', label: 'Priority', match: /^priority$/i },
  { key: 'estimate', label: 'Estimate', match: /^estimate$/i },
];

/** A role comment opens with a bold role tag, like **[Senior developer] Plan**. */
const ROLE_RE = /^\s*\*\*\[([^\]\n]+)\]\s*([^*\n]*?)\s*\*\*/;

const FILE_EXTENSIONS = 'md|mdx|ts|tsx|js|jsx|mjs|cjs|json|ya?ml|html|css|svg|png|sh|txt';
const PATH_RE = new RegExp(
  // a path with a slash (folder/, folder/file.ext) or a bare file with a known extension
  String.raw`(?<![\w/.:@-])(\.{0,2}/?(?:[\w.@\[\]()-]+/)+(?:[\w.@\[\]()-]+\.(?:${FILE_EXTENSIONS})\b)?|[\w.-]+\.(?:${FILE_EXTENSIONS})\b)(?![\w/<-])`,
  'g',
);

/** Strips the generated footer and trailing whitespace from a body. */
function cleanBody(text) {
  return String(text || '')
    .replace(/\r\n/g, '\n')
    .replace(/\n-{3,}\n_Generated by \[Claude Code\][^\n]*_\s*$/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
}

/**
 * Splits a markdown body into [{ heading, text }] by its ## and ### headings.
 * A section keeps its deeper subheadings and ends at a heading of the same or a
 * higher level, or at a --- rule.
 */
function splitSections(body) {
  const lines = cleanBody(body).split('\n');
  const sections = [];
  lines.forEach((line, i) => {
    const h = line.match(/^(#{2,3})\s+(.+?)\s*#*\s*$/);
    if (!h) return;
    const level = h[1].length;
    const text = [];
    for (const next of lines.slice(i + 1)) {
      const nh = next.match(/^(#{1,6})\s/);
      if ((nh && nh[1].length <= level) || /^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(next)) break;
      text.push(next);
    }
    sections.push({ heading: h[2].trim(), text: text.join('\n').trim() });
  });
  return sections;
}

/** @returns {{ userStory: string | null, criteria: string | null, priority: string | null, estimate: string | null }} */
function extractSections(body) {
  const found = splitSections(body);
  const out = {};
  for (const { key, match } of SECTIONS) {
    const s = found.find((f) => match.test(f.heading));
    out[key] = s && s.text && s.text !== '_No response_' ? s.text : null;
  }
  return out;
}

/** Issue and PR numbers referenced as #12, owner/repo#12 or a full GitHub URL to this repo. */
function extractLinks(texts, repo, selfNumber) {
  const numbers = new Set();
  const [owner, name] = repo.toLowerCase().split('/');
  for (const text of texts) {
    const t = String(text || '');
    for (const m of t.matchAll(/https:\/\/github\.com\/([\w.-]+)\/([\w.-]+)\/(?:issues|pull)\/(\d+)/gi)) {
      if (m[1].toLowerCase() === owner && m[2].toLowerCase() === name) numbers.add(Number(m[3]));
    }
    const withoutUrls = t.replace(/https?:\/\/\S+/g, ' ');
    for (const m of withoutUrls.matchAll(/(?:^|[^\w&/#])(?:([\w.-]+)\/([\w.-]+))?#(\d+)\b/g)) {
      if (m[1] && (m[1].toLowerCase() !== owner || m[2].toLowerCase() !== name)) continue;
      numbers.add(Number(m[3]));
    }
  }
  numbers.delete(selfNumber);
  return [...numbers].sort((a, b) => a - b);
}

/** File and folder paths mentioned in the texts, in first-seen order. */
function extractFiles(texts) {
  const files = [];
  for (const text of texts) {
    const t = String(text || '').replace(/https?:\/\/\S+/g, ' ');
    for (const m of t.matchAll(PATH_RE)) {
      const p = m[1].replace(/^\.\//, '');
      if (/^\d+(\.\d+)*$/.test(p) || /^[\w-]+\/[\w-]+$/.test(p) || p.startsWith('/')) continue;
      if (!files.includes(p)) files.push(p);
    }
  }
  return files;
}

/** Role comments plus the owner's own comments, newest first. */
function selectComments(comments, owner) {
  const picked = [];
  let skipped = 0;
  for (const c of comments || []) {
    const body = cleanBody(c.body);
    const login = (c.user && c.user.login) || 'unknown';
    const role = body.match(ROLE_RE);
    const isOwner = login.toLowerCase() === owner.toLowerCase();
    if (!role && !isOwner) {
      skipped += 1;
      continue;
    }
    // Drop the role tag (it's in the header line) and collapse blank runs.
    const rest = role ? body.slice(role[0].length).replace(/^[ \t]*\n/, '') : body;
    const lines = rest
      .split('\n')
      .filter((l, i, all) => l.trim() || (i > 0 && all[i - 1].trim()))
      .filter((l, i) => i > 0 || l.trim());
    picked.push({
      author: login,
      role: role ? role[1].trim() : null,
      title: role ? role[2].trim() || null : null,
      kind: role ? 'role' : 'owner',
      createdAt: c.created_at,
      url: c.html_url,
      lines,
    });
  }
  picked.sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt)));
  return { picked, skipped };
}

function excerpt(lines, n) {
  return { excerpt: lines.slice(0, n), cutLines: Math.max(0, lines.length - n) };
}

function render(brief) {
  const out = [];
  out.push(`#${brief.number} ${brief.title}`);
  out.push(`State: ${brief.state} · Labels: ${brief.labels.length ? brief.labels.join(', ') : 'none'}`);
  out.push(brief.url);
  for (const { key, label } of SECTIONS) {
    out.push('', `## ${label}`);
    const s = brief.sections[key];
    if (!s) out.push(`(missing: no "${label}" section in the issue body)`);
    else {
      out.push(...s.lines);
      if (s.cutLines) out.push(`… ${s.cutLines} more lines cut; see the issue`);
    }
  }
  out.push('', '## Linked issues and PRs');
  out.push(
    brief.links.length
      ? brief.links.map((l) => (l.title ? `#${l.number} ${l.type === 'pr' ? '(PR) ' : ''}${l.title}${l.state ? ` [${l.state}]` : ''}` : `#${l.number}`)).join('\n')
      : 'none',
  );
  out.push('', '## Files mentioned');
  out.push(brief.files.length ? brief.files.map((f) => `- ${f}`).join('\n') : 'none');
  out.push('', `## Role and owner comments (newest first, ${brief.comments.length} shown)`);
  if (!brief.comments.length) out.push('none');
  for (const c of brief.comments) {
    const who = c.role ? `[${c.role}]${c.title ? ` ${c.title}` : ''}` : 'Owner';
    out.push(`- ${who} · ${c.author} · ${String(c.createdAt).slice(0, 10)} · ${c.url}`);
    for (const l of c.excerpt) out.push(`    ${l}`);
    if (c.cutLines) out.push(`    … ${c.cutLines} more lines`);
  }
  if (brief.cut.length) {
    out.push('', '## Cut to fit');
    for (const note of brief.cut) out.push(`- ${note}`);
    out.push(`Full issue: ${brief.url}`);
  }
  return out.join('\n').split('\n');
}

/**
 * Builds the brief.
 * @param {object} issue    REST issue object
 * @param {object[]} comments REST comment objects
 * @param {object} [opts]   { repo, maxLines, links: { [number]: { title, type, state } } }
 * @returns {{ brief: Brief, text: string }}
 */
function buildBrief(issue, comments, opts = {}) {
  const repo = opts.repo || 'RosePinkDragon/fuzzy-waddle';
  // Leave room for the "Cut to fit" notes that trimming itself adds.
  const maxLines = (opts.maxLines || DEFAULT_MAX_LINES) - 6;
  const owner = opts.owner || repo.split('/')[0];
  const sections = extractSections(issue.body);
  const texts = [issue.body, ...(comments || []).map((c) => c.body)];
  const { picked, skipped } = selectComments(comments, owner);

  /** @type {Brief} */
  const brief = {
    number: issue.number,
    title: issue.title,
    state: issue.state,
    labels: (issue.labels || []).map((l) => (typeof l === 'string' ? l : l.name)),
    url: issue.html_url || `https://github.com/${repo}/issues/${issue.number}`,
    sections: { userStory: null, criteria: null, priority: null, estimate: null },
    links: extractLinks(texts, repo, issue.number).map((n) => ({ number: n, ...((opts.links && opts.links[n]) || {}) })),
    files: extractFiles(texts),
    comments: [],
    cut: [],
  };
  for (const { key } of SECTIONS) {
    brief.sections[key] = sections[key] === null ? null : { lines: sections[key].split('\n'), cutLines: 0 };
  }
  if (skipped) brief.cut.push(`${skipped} comment${skipped === 1 ? '' : 's'} without a role tag from people other than the owner left out`);

  const setComments = (list, n) => {
    brief.comments = list.map(({ lines, ...c }) => ({ ...c, ...excerpt(lines, n) }));
  };
  setComments(picked, EXCERPT_LINES);

  // Trim in steps until it fits: shorter excerpts, then fewer comments, then shorter sections.
  if (render(brief).length > maxLines) {
    setComments(picked, SHORT_EXCERPT_LINES);
    brief.cut.push(`comment excerpts shortened to ${SHORT_EXCERPT_LINES} lines`);
  }
  // Then very long sections down to 40 lines, then older comments, then sections down to 3 lines.
  const trimmed = new Set();
  const trimSections = (floor) => {
    let s;
    const longest = () =>
      SECTIONS.map(({ key }) => brief.sections[key])
        .filter((x) => x && x.lines.length > floor)
        .sort((x, y) => y.lines.length - x.lines.length)[0];
    while (render(brief).length > maxLines && (s = longest())) {
      s.lines.pop();
      s.cutLines += 1;
      trimmed.add(SECTIONS.find(({ key }) => brief.sections[key] === s).label);
    }
  };
  trimSections(40);
  let kept = picked.length;
  while (render(brief).length > maxLines && kept > 0) {
    kept -= 1;
    setComments(picked.slice(0, kept), SHORT_EXCERPT_LINES);
  }
  trimSections(3);
  if (trimmed.size) brief.cut.push(`long sections shortened: ${[...trimmed].join(', ')}`);
  if (kept < picked.length) brief.cut.push(`${picked.length - kept} older comment${picked.length - kept === 1 ? '' : 's'} left out`);
  if (brief.files.length > 20 && render(brief).length > maxLines) {
    brief.cut.push(`${brief.files.length - 20} more file paths left out`);
    brief.files = brief.files.slice(0, 20);
  }

  return { brief, text: render(brief).join('\n') };
}

module.exports = { buildBrief, extractSections, extractLinks, extractFiles, selectComments, cleanBody, DEFAULT_MAX_LINES };
